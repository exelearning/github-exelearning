// The same languages as the editor; English when the browser asks for none of them.
const languages = { en, es, ca, eu, gl, de };
type Lang = keyof typeof languages;
export const lang: Lang = (navigator.languages ?? [navigator.language])
    .map((tag) => tag.toLowerCase().split('-')[0])
    .find((code): code is Lang => code in languages) ?? 'en';
const strings = languages[lang];

export function t(key: keyof typeof en, vars: Record<string, string | number> = {}): string {
    return strings[key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
